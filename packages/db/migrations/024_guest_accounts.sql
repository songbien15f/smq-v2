-- Optional Guest accounts: email + password, a session cookie, and saved drafts.
--
-- Spec docs/specs/guest-accounts.md. An account is its own table, not a password on
-- `guest_contacts`: a contact row is created for whatever email anybody types on an anonymous
-- request, so "a contact exists for this email" proves nothing about who owns it. For the same
-- reason an account never adopts the anonymous requests sent under its email.

CREATE TABLE IF NOT EXISTS guest_accounts (
  id               TEXT PRIMARY KEY,
  email_norm       TEXT NOT NULL UNIQUE,
  password_hash    TEXT NOT NULL,
  first_name       TEXT NOT NULL,
  last_name        TEXT NOT NULL,
  mobile           TEXT NOT NULL,
  created_at       TEXT NOT NULL,
  updated_at       TEXT NOT NULL,
  last_sign_in_at  TEXT
);

-- The `sq_guest` cookie. Only the token's hash is stored: a dump must not hand out a live session.
CREATE TABLE IF NOT EXISTS guest_account_sessions (
  id            TEXT PRIMARY KEY,
  account_id    TEXT NOT NULL REFERENCES guest_accounts(id) ON DELETE CASCADE,
  token_hash    TEXT NOT NULL UNIQUE,
  created_at    TEXT NOT NULL,
  last_seen_at  TEXT NOT NULL,
  expires_at    TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS guest_account_sessions_account_idx ON guest_account_sessions (account_id);
CREATE INDEX IF NOT EXISTS guest_account_sessions_expiry_idx ON guest_account_sessions (expires_at);

-- A design in progress. The id is generated by the page, so a save is an idempotent upsert.
-- No contact details: the same fields the page keeps in localStorage, nothing more.
CREATE TABLE IF NOT EXISTS guest_drafts (
  id           TEXT PRIMARY KEY,
  account_id   TEXT NOT NULL REFERENCES guest_accounts(id) ON DELETE CASCADE,
  design_json  TEXT NOT NULL,
  step         TEXT NOT NULL,
  source_json  TEXT,
  revision_of  TEXT,
  created_at   TEXT NOT NULL,
  updated_at   TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS guest_drafts_account_idx ON guest_drafts (account_id, updated_at);

-- Null = sent anonymously.
ALTER TABLE guest_requests ADD COLUMN IF NOT EXISTS account_id TEXT REFERENCES guest_accounts(id);
CREATE INDEX IF NOT EXISTS guest_requests_account_idx ON guest_requests (account_id, created_at);
