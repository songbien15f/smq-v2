-- Postgres setup for SmartQuote v2.
--
-- Run once, as a superuser, before `pnpm db:migrate`:
--
--   psql -h 127.0.0.1 -U postgres -f scripts/postgres-setup.sql
--
-- On Windows, `psql` is not on the PATH by default:
--   "C:\Program Files\PostgreSQL\18\bin\psql.exe" -h 127.0.0.1 -U postgres -f scripts/postgres-setup.sql
--
-- ## What it creates, and why it is a script rather than something the application does
--
-- The application must not be able to create its own database or role. A connection that can
-- run `CREATE ROLE` is a connection that can grant itself anything, and the credential in
-- `.env` would then be worth far more than the data it guards. So provisioning is a
-- superuser's job, done once, and recorded here rather than in someone's shell history.

-- The role the application connects as. It owns nothing except what the migrations create.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'smartquote') THEN
    CREATE ROLE smartquote LOGIN PASSWORD 'smartquote';
    RAISE NOTICE 'role smartquote created';
  ELSE
    RAISE NOTICE 'role smartquote already exists';
  END IF;
END
$$;

-- The database, owned by that role, so the migrations can create tables without a superuser.
SELECT 'CREATE DATABASE smartquote OWNER smartquote'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'smartquote')
\gexec

-- The migrations need to create tables, indexes and (on Postgres) rules and triggers inside
-- the database they own. Nothing outside it.
\connect smartquote

GRANT ALL ON SCHEMA public TO smartquote;

-- The `bigint`-free, tenant-column-stays design means nothing else is needed: no extensions,
-- no procedural language beyond the plpgsql that ships with Postgres, and no sequence the
-- application relies on. Identifiers are uuids generated by the application.
\echo ''
\echo 'Done. Now, in the repository:'
\echo '  DB_DRIVER=postgres DATABASE_URL=postgres://smartquote:smartquote@127.0.0.1:5432/smartquote pnpm db:migrate'
